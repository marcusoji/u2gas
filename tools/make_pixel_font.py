# The post table is latin-1 only, so glyphs need ASCII names. These are the
# standard Adobe glyph names; the cmap below maps codepoints to them.
NAMES = {
    " ": "space", ".": "period", ",": "comma", ":": "colon", ";": "semicolon",
    "!": "exclam", "?": "question", "-": "hyphen", "_": "underscore",
    "+": "plus", "=": "equal", "/": "slash", "\\": "backslash",
    "(": "parenleft", ")": "parenright", "[": "bracketleft", "]": "bracketright",
    "'": "quotesingle", '"': "quotedbl", "*": "asterisk", "#": "numbersign",
    "%": "percent", "&": "ampersand", "@": "at", "<": "less", ">": "greater",
    "$": "dollar", "{": "braceleft", "}": "braceright", "|": "bar",
    "~": "asciitilde", "^": "asciicircum", "`": "grave",
    "\u00d7": "multiply", "\u00b7": "periodcentered",
    "\u2014": "emdash", "\u20a6": "uni20A6",
}


def glyph_name(ch: str) -> str:
    if ch in NAMES:
        return NAMES[ch]
    if ch.isalnum() and ord(ch) < 128:
        return ch
    return "uni%04X" % ord(ch)


def contours(bitmap, bold=False):
    """One square per lit pixel. Bold smears each pixel right by a third."""
    out = []
    for r, row in enumerate(bitmap):
        for c, ch in enumerate(row):
            if ch != "1":
                continue
            x0, y0 = c * PX, (CELL_H - 1 - r) * PX
            x1, y1 = x0 + PX, y0 + PX
            if bold:
                x1 += PX // 3
            out.append([(x0, y0), (x1, y0), (x1, y1), (x0, y1)])
    return out


def build(bold: bool):
    chars = [chr(i) for i in range(0x20, 0x7F)] + ["\u00d7", "\u00b7", "\u2014", "\u20a6"]
    chars = [c for c in dict.fromkeys(chars) if c in G]

    glyphs, advances, cmap = {}, {}, {}

    for name in [".notdef"] + [glyph_name(c) for c in chars]:
        pen = TTGlyphPen(None)

        if name == ".notdef":
            # A hollow box, so a missing glyph is obviously missing.
            for box in ([(0, 0), (500, 0), (500, 700), (0, 700)],
                        [(100, 100), (100, 600), (400, 600), (400, 100)]):
                pen.moveTo(box[0])
                for p in box[1:]:
                    pen.lineTo(p)
                pen.closePath()
        else:
            ch = next(c for c in chars if glyph_name(c) == name)
            cmap[ord(ch)] = name
            for square in contours(G[ch], bold):
                pen.moveTo(square[0])
                for p in square[1:]:
                    pen.lineTo(p)
                pen.closePath()

        glyphs[name] = pen.glyph()
        advances[name] = ADV          # monospaced by construction

    weight = 700 if bold else 400
    style = "Bold" if bold else "Regular"

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(list(glyphs))
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (advances[n], 0) for n in glyphs})
    fb.setupHorizontalHeader(ascent=ASC, descent=-DESC)
    fb.setupNameTable({
        "familyName": "U2 Pixel",
        "styleName": style,
        "uniqueFontIdentifier": f"U2Pixel-{style}",
        "fullName": f"U2 Pixel {style}",
        "psName": f"U2Pixel-{style}",
        "version": "1.0",
        "manufacturer": "Generated for U2GAS",
        "licenseDescription":
            "Reconstruction of a 5x7 dot-matrix grid, generated from scratch. "
            "Not the licensed face from the U2GAS Figma file.",
    })
    fb.setupOS2(sTypoAscender=ASC, sTypoDescender=-DESC,
                usWinAscent=ASC, usWinDescent=DESC,
                sCapHeight=CELL_H * PX, achVendID="U2GS",
                usWeightClass=weight, fsType=0)
    fb.setupPost(isFixedPitch=1)
    return fb


def main(outdir: str):
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)

    for bold in (False, True):
        fb = build(bold)
        weight = "700" if bold else "400"

        ttf = out / f"u2-pixel-{weight}.ttf"
        fb.save(str(ttf))

        # WOFF2 needs brotli, which is not installed here. WOFF uses zlib and
        # is supported everywhere; convert to WOFF2 later for ~20% less.
        fb.font.flavor = "woff"
        woff = out / f"u2-pixel-{weight}.woff"
        fb.save(str(woff))

        print(f"  {woff.name}  {woff.stat().st_size:>6,} bytes")
        print(f"  {ttf.name}   {ttf.stat().st_size:>6,} bytes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "web/public/fonts")
