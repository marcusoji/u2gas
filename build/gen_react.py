"""Generate web/src/figma from docs/u2gas-all-screens.html.

The supplied gallery file is the design source of truth: every artboard is one
`<figure class="slot">` inside it, each holding a `.frame` whose children are
absolutely positioned from Figma's own coordinates. This script turns those
frames into the markup the app renders, so the product and the reference are
literally the same drawing:

  web/src/figma/assets.ts            the 12 pictures, stored once each
  web/src/figma/screens/<Name>.ts    one module per artboard
  web/src/figma/artboards.ts         node -> {name, app, height, html}

Run it after the gallery is regenerated, then `bash scripts/check-figma-parity.sh`
proves the copy still matches.

  python3 build/gen_react.py
"""
