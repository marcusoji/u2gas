TS_HEADER = (
    "// Generated by build/gen_react.py from docs/u2gas-all-screens.html.\n"
    "// Do not edit: correct the gallery and re-run the generator.\n"
)


def parse_source():
    text = SOURCE.read_text()
    css = STYLE.search(text).group(1)
    # The gallery defines every picture once as a custom property; the app
    # imports them from assets.ts instead.
    assets = []
    for name, data in ASSET.findall(css):
        assets.append((name.lstrip("-"), data))

    frames = []
    for app, node, height, html, _cap, _em in FIGURE.findall(text):
        frames.append({"app": app, "node": node, "height": int(height), "html": html})
    return assets, frames


def camel(node, title):
    name = NODE_TO_SCREEN.get(node)
    if not name:
        raise KeyError("no module name pinned for node %s" % node)
    return name


def emit_assets(assets):
    lines = [
        TS_HEADER,
        "// The pictures the artboards embed, one copy each.",
        "",
    ]
    lookup = {}
    for index, (key, data) in enumerate(assets):
        ident = f"a{index}"
        lookup[key] = ident
        lines.append(f'export const {ident} = "{data}";')
    lines.append("")
    return {"assets.ts": "\n".join(lines)}, lookup


def asset_ident(index):
    return f"a{index}"


def rewrite_assets(html, lookup):
    """Bind the gallery's `--src:var(--aN)` pictures to the imported asset.

    The file draws each picture as `<span class="asset-img" style="--src:var(--aN)">`
    and paints it with `.asset-img { background-size: contain; background-position:
    center }`. The app imports the same bytes from assets.ts, so the only thing
    that has to change is where `--src` points: `var(--aN)` becomes the data URI.

    Everything else is left exactly as the file wrote it. Rebuilding these as
    `<img src object-fit:contain>` instead looks equivalent but is not: Chromium
    centres the scaled picture at a different subpixel offset than
    `background-size: contain` does, so every cropped photo rasterised a pixel
    off (1:2210 0.88%, 1:1438 0.53%). Keeping the file's own mechanism removes
    the difference entirely.
    """
    pattern = re.compile(r"--src:var\(--a(\d+)\)")

    def to_asset(match):
        ident = lookup.get("a" + match.group(1))
        if ident is None:
            return match.group(0)
        # Single quotes so the url() nests inside the double-quoted style attr.
        return "--src:url('${A.%s}')" % ident

    return pattern.sub(to_asset, html)


def emit_screens(frames, lookup):
    written = set()
    out = {}
    for frame in frames:
        name = camel(frame["node"], frame["_title"])
        frame["_name"] = name
        html = rewrite_assets(frame["html"], lookup)
        # Escape the template literal, but the `\${A.aN}` references this
        # generator just inserted are code, not text: park them so the escaping
        # cannot touch them.
        marker = "\x00"
        html = re.sub(r"\$\{A\.(a\d+)\}", lambda m: marker + m.group(1) + marker, html)
        html = html.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
        html = re.sub(marker + r"(a\d+)" + marker, lambda m: "${A." + m.group(1) + "}", html)
        out[f"screens/{name}.ts"] = (
            TS_HEADER
            + f"// Screen: {frame['_title']}  node {frame['node']}  app {frame['app']}\n"
            + 'import * as A from "../assets";\n\n'
            + f'export const node = "{frame["node"]}";\n'
            + f"export const height = {frame['height']};\n"
            + f"export const html = `{html}`;\n"
        )
        written.add(name)
    return out


def emit_artboards(frames):
    imports = "\n".join(
        f'import * as {f["_name"]} from "./screens/{f["_name"]}";' for f in frames
    )
    entries = "\n".join(
        '  "%s": { name: %s, node: "%s", app: "%s", height: %d, html: %s.html },'
        % (
            f["node"],
            '"' + f["_title"].replace("\\", "\\\\").replace('"', '\\"') + '"',
            f["node"],
            f["app"],
            f["height"],
            f["_name"],
        )
        for f in frames
    )
    body = f"""{TS_HEADER}
//
// Every artboard in the supplied gallery, as the markup the screens use, so
// the product and the reference cannot drift apart.

{imports}

export interface FigmaArtboard {{
  name: string;
  node: string;
  app: string;
  height: number;
  html: string;
}}

export const artboards: Record<string, FigmaArtboard> = {{
{entries}
}};

export const byName = (name: string): FigmaArtboard | undefined =>
  Object.values(artboards).find((a) => a.name === name);
"""
    return {"artboards.ts": body}


def build():
    """Return the generated files as a path -> text map, relative to src/figma."""
    assets, frames = parse_source()
    if not frames:
        sys.exit("no frames found in %s" % SOURCE)

    titles = re.findall(r"<figcaption><b>[^<]*</b>([^<]*)<em>", SOURCE.read_text())
    if len(titles) != len(frames):
        sys.exit("caption/title mismatch: %d vs %d" % (len(titles), len(frames)))
    for frame, title in zip(frames, titles):
        frame["_title"] = title.strip()

    generated, lookup = emit_assets(assets)
    generated.update(emit_screens(frames, lookup))
    generated.update(emit_artboards(frames))
    return generated


def write():
    generated = build()
    for rel, text in generated.items():
        target = OUT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    stale = [
        p.relative_to(OUT).as_posix()
        for p in (OUT / "screens").glob("*.ts")
        if p.relative_to(OUT).as_posix() not in generated
    ]
    print(f"assets: 1   screens: {len(generated) - 2}")
    if stale:
        print("no longer generated:", ", ".join(sorted(stale)))
    return generated


def main():
    generated = build()
    if "--check" in sys.argv:
        drifted = [
            rel for rel, text in generated.items()
            if not (OUT / rel).exists() or (OUT / rel).read_text() != text
        ]
        on_disk = {
            p.relative_to(OUT).as_posix()
            for p in (OUT / "screens").glob("*.ts")
        }
        extra = sorted(on_disk - set(generated))
        print(f"artboards in the app: {len(generated) - 2}")
        if drifted or extra:
            print(f"DRIFT: {len(drifted)} differ, {len(extra)} unexpected")
            for rel in (drifted + extra)[:10]:
                print("  ", rel)
            sys.exit(1)
        print("identical: the product and the reference are the same drawing")
        return
    write()


if __name__ == "__main__":
    main()
